import { chromium } from '/home/dobo/work/_worktrees/cat_de_roman_esti/feat__v95-discovery-and-game-quality/frontend/node_modules/playwright/index.mjs';
import fs from 'node:fs';
import crypto from 'node:crypto';
const out = '/home/dobo/work/_temp/feat__v95-discovery-and-game-quality/gui';
const browser = await chromium.launch({headless: true});
const page = await browser.newPage({viewport:{width:390,height:844},locale:'ro-RO',reducedMotion:'reduce'});
await page.goto('http://127.0.0.1:8150/alchimie');
const created=page.waitForResponse(r=>r.url().endsWith('/api/alchimie/explore')&&r.request().method()==='POST');
await page.getByRole('button',{name:'Începe explorarea →'}).click();
const state=await (await created).json();
if(state.world.total_concepts!==247||state.world.total_recipes!==342)throw Error('Stale world');
await page.locator('.alchemy-inventory-grid').getByRole('button',{name:/^Făină(?:,|$)/}).click();
const empty=page.waitForResponse(r=>r.url().endsWith('/combine')&&r.request().method()==='POST');
await page.locator('.alchemy-inventory-grid').getByRole('button',{name:/^Cheag alimentar(?:,|$)/}).click();
await empty;
await page.getByRole('button',{name:'Cheag alimentar, încercat fără rezultat cu Făină'}).waitFor();
await page.screenshot({path:out+'/final-preview-mobile.png',fullPage:true});
const picture=fs.readFileSync(out+'/final-preview-mobile.png');
fs.writeFileSync(out+'/final-preview-capture.json',JSON.stringify({url:'http://127.0.0.1:8150/alchimie',world:state.world,viewport:{width:390,height:844},emptyPairMarkerObserved:true,screenshot:'final-preview-mobile.png',sha256:crypto.createHash('sha256').update(picture).digest('hex')},null,2)+'\n');
await browser.close();
