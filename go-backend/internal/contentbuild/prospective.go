const prospectiveLantCaptionSchema = "cat-prospective-lant-captions-1"

func readDirect(path string, max int64) ([]byte, error) {
	return readDirectAfterOpen(path, max, nil)
}

func readDirectAfterOpen(path string, max int64, afterOpen func() error) ([]byte, error) {
	f, err := openNoSymlinkPath(path, unix.O_RDONLY, 0)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() || info.Size() > max {
		return nil, fmt.Errorf("source exceeds %d byte bound or is not a regular file", max)
	}
	if afterOpen != nil {
		if err := afterOpen(); err != nil {
			return nil, err
		}
	}
	b, err := io.ReadAll(io.LimitReader(f, max+1))
	if err != nil {
		return nil, err
	}
	if int64(len(b)) > max {
		return nil, fmt.Errorf("source exceeds byte bound")
	}
	return b, nil
}

func boundObject(path string, max int64) (map[string]any, []byte, error) {
	b, err := readDirect(path, max)
	if err != nil {
		return nil, nil, err
	}
	m, err := decodeObject(b)
	return m, b, err
}

func binding(display string, data []byte) map[string]any {
	return map[string]any{"path": display, "sha256": SHA256(data), "bytes": len(data)}
}

const excludedServingEmbed = "go-backend/internal/content/bundled.json"

type goListModule struct {
	Main bool
	Dir  string
}

type goListPackage struct {
	Dir        string
	Module     *goListModule
	GoFiles    []string
	CgoFiles   []string
	CFiles     []string
	CXXFiles   []string
	MFiles     []string
	HFiles     []string
	FFiles     []string
	SFiles     []string
	SysoFiles  []string
	EmbedFiles []string
}

func cleanGoListEnv() []string {
	blocked := map[string]bool{"GOENV": true, "GOFLAGS": true, "GONOSUMDB": true, "GOPRIVATE": true, "GOPROXY": true, "GOSUMDB": true, "GOWORK": true}
	env := make([]string, 0, len(os.Environ())+5)
	for _, item := range os.Environ() {
		key, _, _ := strings.Cut(item, "=")
		if !blocked[key] {
			env = append(env, item)
		}
	}
	return append(env, "GOENV=off", "GOFLAGS=", "GOPROXY=off", "GOSUMDB=off", "GOWORK=off")
}

// nativeProducerPaths asks the pinned Go tool for the real production
// dependency closure of cat-content. Test files are never in these fields.
// The installed serving bundle is the one deliberate exclusion: this preview
// constructs content.Content directly and never calls content.Load or Decode,
// so those generated bytes cannot affect parsing, graph construction, pack
// validation, edge selection or captions. Its production digest declaration
// remains covered through content/digest.go.
func nativeProducerPaths(root string) ([]string, error) {
	moduleDir := filepath.Join(root, "go-backend")
	goTool := filepath.Join(runtime.GOROOT(), "bin", "go")
	cmd := exec.Command(goTool, "list", "-deps", "-json", "-mod=readonly", "-buildvcs=false", "./cmd/cat-content")
	cmd.Dir = moduleDir
	cmd.Env = cleanGoListEnv()
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return nil, err
	}
	var stderr strings.Builder
	cmd.Stderr = &stderr
	if err := cmd.Start(); err != nil {
		return nil, err
	}
	paths := []string{filepath.Join(moduleDir, "go.mod"), filepath.Join(moduleDir, "go.sum")}
	decoder := json.NewDecoder(stdout)
	for decoder.More() {
		var pkg goListPackage
		if err := decoder.Decode(&pkg); err != nil {
			_ = cmd.Wait()
			return nil, fmt.Errorf("decode Go producer closure: %w", err)
		}
		if pkg.Module == nil || !pkg.Module.Main {
			continue
		}
		relDir, err := filepath.Rel(moduleDir, pkg.Dir)
		if err != nil || relDir == ".." || strings.HasPrefix(relDir, ".."+string(filepath.Separator)) {
			_ = cmd.Wait()
			return nil, fmt.Errorf("local producer package escaped main module: %s", pkg.Dir)
		}
		groups := [][]string{pkg.GoFiles, pkg.CgoFiles, pkg.CFiles, pkg.CXXFiles, pkg.MFiles, pkg.HFiles, pkg.FFiles, pkg.SFiles, pkg.SysoFiles, pkg.EmbedFiles}
		for _, names := range groups {
			for _, name := range names {
				path := filepath.Join(pkg.Dir, name)
				rel, err := filepath.Rel(root, path)
				if err != nil {
					_ = cmd.Wait()
					return nil, err
				}
				if filepath.ToSlash(rel) != excludedServingEmbed {
					paths = append(paths, path)
				}
			}
		}
	}
	if err := cmd.Wait(); err != nil {
		return nil, fmt.Errorf("enumerate Go producer closure: %w: %s", err, strings.TrimSpace(stderr.String()))
	}
	sort.Strings(paths)
	compact := paths[:0]
	for _, path := range paths {
		if len(compact) == 0 || compact[len(compact)-1] != path {
			compact = append(compact, path)
		}
	}
	return compact, nil
}

func nativeSourceBindings(root string) ([]any, error) {
	paths, err := nativeProducerPaths(root)
	if err != nil {
		return nil, err
	}
	out := make([]any, 0, len(paths))
	for _, path := range paths {
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return nil, err
		}
		info, err := os.Lstat(path)
		if err != nil || !info.Mode().IsRegular() {
			return nil, fmt.Errorf("native source must be a regular file: %s", filepath.ToSlash(rel))
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		out = append(out, binding(filepath.ToSlash(rel), b))
	}
	return out, nil
}

func canonicalRoot(root string) (string, error) {
	abs, err := filepath.Abs(root)
	if err != nil {
		return "", err
	}
	resolved, err := filepath.EvalSymlinks(abs)
	if err != nil {
		return "", err
	}
	info, err := os.Stat(resolved)
	if err != nil || !info.IsDir() {
		return "", fmt.Errorf("repository root must resolve to a directory")
	}
	return resolved, nil
}

// BuildProspectiveLantCaptions validates an explicit KG/pack pair and emits an
// unapproved preview artifact. It deliberately does not build serving content
// or consult/rewrite installed catalog, ranking, source or rail pins.
func BuildProspectiveLantCaptions(root, kgPath, packPath string) ([]byte, error) {
	if runtime.Version() != "go1.27.3" {
		return nil, fmt.Errorf("prospective preview requires go1.27.3, got %s", runtime.Version())
	}
	root, err := canonicalRoot(root)
	if err != nil {
		return nil, err
	}
	kg, kgBytes, err := boundObject(kgPath, 16<<20)
	if err != nil {
		return nil, fmt.Errorf("kg: %w", err)
	}
	if errors := validateFixture(kg); len(errors) > 0 {
		return nil, fmt.Errorf("fixture invalid: %s", errorSummary(errors))
	}
	pack, packBytes, err := boundObject(packPath, 8<<20)
	if err != nil {
		return nil, fmt.Errorf("pack: %w", err)
	}
	c, err := parsedGraph(kg)
	if err != nil {
		return nil, err
	}
	g := graph.New(c)
	if errors := validatePack(pack, g); len(errors) > 0 {
		return nil, fmt.Errorf("pack invalid: %s", errorSummary(errors))
	}
	rubricPath := filepath.Join(root, "docs", "CRITIQUE_RUBRIC.md")
	rubricBytes, err := readDirect(rubricPath, 1<<20)
	if err != nil {
		return nil, fmt.Errorf("required reviewed rubric: %w", err)
	}
	if TextSHA256(rubricBytes) != RubricSHA256 {
		return nil, fmt.Errorf("reviewed rubric digest drift")
	}
	rules, err := frozenRules()
	if err != nil {
		return nil, err
	}
	rulesPath := filepath.Join(root, "go-backend", "internal", "contentbuild", "rules_unicode15.json")
	rootRules, err := readDirect(rulesPath, 8<<20)
	if err != nil || SHA256(rootRules) != rulesSHA256 || SHA256(rootRules) != SHA256(rulesBytes) {
		return nil, fmt.Errorf("root frozen rules differ from native rules")
	}
	provenancePath := filepath.Join(root, "go-backend", "internal", "contentbuild", "rules_provenance.json")
	rootProvenance, err := readDirect(provenancePath, 1<<20)
	if err != nil || SHA256(rootProvenance) != SHA256(provenanceBytes) {
		return nil, fmt.Errorf("root frozen rules provenance differs from native provenance")
	}
	native, err := nativeSourceBindings(root)
	if err != nil {
		return nil, err
	}
	captions := lantCaptions(g, rules)
	artifact := map[string]any{
		"schema":        prospectiveLantCaptionSchema,
		"purpose":       "unapproved_native_preview_only",
		"game":          "lant",
		"qualification": "Native derivation and validation only; no content, source, ranking, rail, installation or serving approval.",
		"inputs": map[string]any{
			"kg":               binding(kgPath, kgBytes),
			"pack":             binding(packPath, packBytes),
			"rubric":           binding("docs/CRITIQUE_RUBRIC.md", rubricBytes),
			"rules_unicode15":  binding("go-backend/internal/contentbuild/rules_unicode15.json", rootRules),
			"rules_provenance": binding("go-backend/internal/contentbuild/rules_provenance.json", rootProvenance),
			"native_sources":   native,
			"go_version":       runtime.Version(),
		},
		"counts":   map[string]any{"directed_edges": len(captions)},
		"captions": captions,
	}
	b, err := Canonical(artifact)
	return append(b, '\n'), err
}

// WriteProspectiveLantCaptions writes a new private evidence artifact outside
// the source tree. Existing files and repository/serving paths are never used.
func WriteProspectiveLantCaptions(root, kgPath, packPath, out string) error {
	return writeProspectiveLantCaptionsBeforeCreate(root, kgPath, packPath, out, nil)
}

func writeProspectiveLantCaptionsBeforeCreate(root, kgPath, packPath, out string, beforeCreate func() error) error {
	root, err := canonicalRoot(root)
	if err != nil {
		return err
	}
	out, err = filepath.Abs(out)
	if err != nil {
		return err
	}
	parent := filepath.Dir(out)
	resolvedParent, err := filepath.EvalSymlinks(parent)
	if err != nil {
		return err
	}
	if resolvedParent != filepath.Clean(parent) {
		return fmt.Errorf("prospective preview output parent must not traverse symlinks")
	}
	physicalOut := filepath.Join(resolvedParent, filepath.Base(out))
	rel, err := filepath.Rel(root, physicalOut)
	if err != nil {
		return err
	}
	if rel == "." || rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return fmt.Errorf("prospective preview output must be outside repository root")
	}
	b, err := BuildProspectiveLantCaptions(root, kgPath, packPath)
	if err != nil {
		return err
	}
	if beforeCreate != nil {
		if err := beforeCreate(); err != nil {
			return err
		}
	}
	f, err := openNoSymlinkPath(physicalOut, unix.O_WRONLY|unix.O_CREAT|unix.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	if _, err = f.Write(b); err == nil {
		err = f.Sync()
	}
	if closeErr := f.Close(); err == nil {
		err = closeErr
	}
	return err
}

func openNoSymlinkPath(path string, flags int, mode uint32) (*os.File, error) {
	if !filepath.IsAbs(path) || filepath.Clean(path) != path {
		return nil, fmt.Errorf("path must be absolute and canonical without symlinks")
	}
	resolved, err := filepath.EvalSymlinks(path)
	if err != nil && flags&unix.O_CREAT == 0 {
		return nil, fmt.Errorf("resolve canonical path without symlinks: %w", err)
	}
	if err == nil && resolved != path {
		return nil, fmt.Errorf("path must be absolute and canonical without symlinks")
	}
	if flags&unix.O_CREAT != 0 {
		resolvedParent, parentErr := filepath.EvalSymlinks(filepath.Dir(path))
		if parentErr != nil {
			return nil, fmt.Errorf("resolve canonical parent without symlinks: %w", parentErr)
		}
		if resolvedParent != filepath.Dir(path) {
			return nil, fmt.Errorf("path must be absolute and canonical without symlinks")
		}
	}
	rootFD, err := unix.Open(string(filepath.Separator), unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC|unix.O_NOFOLLOW, 0)
	if err != nil {
		return nil, err
	}
	rel := strings.TrimPrefix(path, string(filepath.Separator))
	how := &unix.OpenHow{
		Flags:   uint64(flags | unix.O_NOFOLLOW | unix.O_CLOEXEC),
		Mode:    uint64(mode),
		Resolve: uint64(unix.RESOLVE_BENEATH | unix.RESOLVE_NO_SYMLINKS),
	}
	fd, openErr := unix.Openat2(rootFD, rel, how)
	_ = unix.Close(rootFD)
	if openErr != nil {
		return nil, fmt.Errorf("open complete path without symlinks: %w", openErr)
	}
	return os.NewFile(uintptr(fd), path), nil
}
